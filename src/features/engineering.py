def canonicalise_categories(df: pd.DataFrame, alias_map: dict = None) -> pd.DataFrame:
    """Fold the case-and-alias variants found by the profiler.

    `CA`, `ca` and `California` are one value. Left alone, a one-hot
    encoder learns three weak features instead of one strong one, and
    every segment-level scenario report splits California across three
    rows. Uses the profiler's explicit alias table, not fuzzy matching.
    """
    from src.data.profiler import KNOWN_ALIASES

    alias_map = alias_map or KNOWN_ALIASES
    out = df.copy()
    for col in ("state",):
        if col not in out.columns:
            continue
        folded = out[col].astype(str).str.strip().str.casefold()
        out[col] = folded.map(lambda v: alias_map.get(v, v)).str.upper()
        out.loc[df[col].isna(), col] = np.nan
    return out


