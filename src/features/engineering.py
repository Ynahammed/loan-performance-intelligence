"""
Dynamic, column-aware feature engineering for loan risk.

THE ONE RULE THAT MATTERS
-------------------------
This is a panel. Every history feature is computed with an expanding
window over rows 1..t for the row at t -- never t+1 onward. At scoring
time for row t we know everything up to and including t, and the targets
describe t+1..t+12, so including row t itself is correct and NOT leakage.
Using `.rolling()` without grouping, or any centred window, would be.
`tests/test_features.py` pins this with a fixture whose future is
deliberately explosive.

WHAT THIS ADDS OVER THE RAW COLUMNS
-----------------------------------
Three families, each earning its place:

  AMORTISATION   Where is this loan against its own schedule? A loan
                 paying ahead of schedule behaves differently from one
                 that has been capitalised. `amortisation_gap` is the
                 signed difference between actual and scheduled balance
                 ratio, reusing the same closed-form projection the
                 transition engine uses for forward simulation.

  RATE INCENTIVE The phase-1 transition model scored ROC-AUC ~0.50 on
                 prepayment -- no signal whatsoever. That is expected:
                 prepayment is driven by the gap between the borrower's
                 rate and what they could refinance into, and no column
                 in the pack carries a market rate. We reconstruct one
                 from the pack itself: the mean origination rate of loans
                 originated in each calendar month. `rate_incentive` is
                 the borrower's rate minus that. Positive means paying
                 above market, which is the refinance motive.

  DELINQUENCY    Current status is one frame of a film. A loan that has
  HISTORY        never missed a payment and one that has cured twice look
                 identical in `current_status` and completely different
                 in risk.

Features are created only if their source columns exist, so the pipeline
survives the organizer's real pack having a different schema. Every
feature is recorded in a manifest (name, formula, sources, rationale)
that feeds the model card.

PHASE: 3
STATUS: implemented.
"""
from __future__ import annotations

import logging
from dataclasses import dataclass, field
from pathlib import Path

import numpy as np
import pandas as pd

from src.config import LOAN_ID_COLUMN, TIME_COLUMN

logger = logging.getLogger(__name__)

DPD_STATES = ("30DPD", "60DPD", "90DPD")
TERMINAL_STATES = ("Default", "Prepaid")

# Ordinal midpoints for the banded credit attributes. Banded strings are
# one-hot encoded by default, which throws away their ordering; a model
# should know that 620-659 sits below 660-699.
BAND_MIDPOINTS = {
    "credit_score_band": {
        "<620": 600, "620-659": 640, "660-699": 680, "700-739": 720,
        "740-779": 760, "780+": 800,
    },
    "ltv_band": {
        "<=60": 55, "61-70": 65, "71-80": 75, "81-90": 85, "91-95": 93,
        ">95": 98,
    },
    "dti_band": {
        "<=30": 25, "31-36": 33, "37-43": 40, "44-50": 47, ">50": 55,
    },
}


@dataclass
class FeatureManifest:
    """Every engineered feature, why it exists, and what it came from."""

    entries: list = field(default_factory=list)
    skipped: list = field(default_factory=list)

    def add(self, name, sources, formula, rationale, family):
        self.entries.append(
            {
                "feature": name,
                "family": family,
                "sources": ", ".join(sources),
                "formula": formula,
                "rationale": rationale,
            }
        )

    def skip(self, name, missing):
        self.skipped.append({"feature": name, "missing_columns": ", ".join(missing)})

    def to_frame(self) -> pd.DataFrame:
        return pd.DataFrame(self.entries)

    def feature_names(self) -> list:
        return [e["feature"] for e in self.entries]

    def to_markdown(self) -> str:
        lines = [
            "# Feature Manifest",
            "",
            "Generated by `src/features/engineering.py`. Every feature below "
            "is computed with an expanding window over a loan's own history "
            "up to and including the row being scored -- never beyond it.",
            "",
        ]
        for family in dict.fromkeys(e["family"] for e in self.entries):
            lines.append("## " + family)
            lines.append("")
            for e in self.entries:
                if e["family"] != family:
                    continue
                lines.append("**`{}`** — {}".format(e["feature"], e["rationale"]))
                lines.append("")
                lines.append("    {}".format(e["formula"]))
                lines.append("")
        if self.skipped:
            lines.append("## Not created (source columns absent)")
            lines.append("")
            for s in self.skipped:
                lines.append("- `{}` — needs {}".format(s["feature"], s["missing_columns"]))
        return "\n".join(lines)


def _has(df: pd.DataFrame, *cols) -> bool:
    return all(c in df.columns for c in cols)


def _missing(df: pd.DataFrame, cols) -> list:
    return [c for c in cols if c not in df.columns]


